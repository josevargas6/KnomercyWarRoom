local function plan(id, state, archetypes, action, why, switchIf, stop, requires, assignments)
    local accepted = {}
    for _, archetype in ipairs(archetypes or {}) do accepted[archetype] = true end
    return {
        id = id,
        state = state or "ANY",
        archetypes = accepted,
        action = action,
        why = why,
        switchIf = switchIf,
        stop = stop,
        requires = requires or {},
        assignments = assignments or {},
        reviewed = true,
    }
end

